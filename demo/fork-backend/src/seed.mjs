// Phase B: on the standalone demo chain, deploy the Gate 1 contracts and create clearly labelled demo
// activity. Every action here is an ordinary transaction on the private demo chain.
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Contract, ContractFactory, Interface, NonceManager, SigningKey, Wallet, getAddress, parseEther, parseUnits } from './deps.mjs'
import { ADDR } from './config.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const artifact = (name) => JSON.parse(readFileSync(join(HERE, '..', 'artifacts', `${name}.json`), 'utf8'))
const hex = (n) => '0x' + BigInt(n).toString(16)
const DAY = 86400

const ERC20 = ['function approve(address,uint256) returns (bool)', 'function transfer(address,uint256) returns (bool)', 'function balanceOf(address) view returns (uint256)']
const SAFE = new Interface([
  'function setup(address[] owners,uint256 threshold,address to,bytes data,address fallbackHandler,address paymentToken,uint256 payment,address paymentReceiver)',
  'function execTransaction(address to,uint256 value,bytes data,uint8 operation,uint256 safeTxGas,uint256 baseGas,uint256 gasPrice,address gasToken,address refundReceiver,bytes signatures) payable returns (bool)',
  'function getTransactionHash(address to,uint256 value,bytes data,uint8 operation,uint256 safeTxGas,uint256 baseGas,uint256 gasPrice,address gasToken,address refundReceiver,uint256 nonce) view returns (bytes32)',
  'function nonce() view returns (uint256)', 'function getThreshold() view returns (uint256)', 'function VERSION() view returns (string)',
])
const FACTORY = new Interface([
  'function createProxyWithNonce(address singleton, bytes initializer, uint256 saltNonce) returns (address proxy)',
])

/** Throwaway demo keys, generated on first boot and kept only in the server's state directory. */
export function generateKeys() {
  const w = () => Wallet.createRandom().privateKey
  return {
    note: 'DEMO CHAIN ONLY. Throwaway keys generated by the fork backend. Never fund these on a real network.',
    deployer: w(), faucet: w(), sponsorBot: w(),
    ownerSigners: [w(), w(), w()], guardianSigners: [w(), w(), w()],
    lockerBots: [w(), w(), w()],
  }
}

async function deploySafe(provider, deployer, signerKeys, salt) {
  const owners = signerKeys.map((k) => new Wallet(k).address)
  const init = SAFE.encodeFunctionData('setup', [owners, 2, '0x0000000000000000000000000000000000000000', '0x', ADDR.SAFE_FALLBACK, '0x0000000000000000000000000000000000000000', 0, '0x0000000000000000000000000000000000000000'])
  const factory = new Contract(ADDR.SAFE_FACTORY, FACTORY, deployer)
  const proxy = await factory.createProxyWithNonce.staticCall(ADDR.SAFE_L2_SINGLETON, init, salt)
  await (await factory.createProxyWithNonce(ADDR.SAFE_L2_SINGLETON, init, salt)).wait()
  const safe = new Contract(proxy, SAFE, provider)
  if (Number(await safe.getThreshold()) !== 2) throw new Error('Safe setup failed')
  return { address: getAddress(proxy), owners, version: await safe.VERSION() }
}

/** Executes a Safe transaction signed by two of the throwaway demo signers. */
async function safeExec(provider, relayer, safeAddress, signerKeys, to, data) {
  const safe = new Contract(safeAddress, SAFE, relayer)
  const zero = '0x0000000000000000000000000000000000000000'
  const nonce = await safe.nonce()
  const hash = await safe.getTransactionHash(to, 0, data, 0, 0, 0, 0, zero, zero, nonce)
  const signers = signerKeys.slice(0, 2).map((k) => new SigningKey(k)).sort((a, b) => (
    BigInt(new Wallet(a.privateKey).address) < BigInt(new Wallet(b.privateKey).address) ? -1 : 1
  ))
  const sigs = '0x' + signers.map((s) => {
    const sig = s.sign(hash)
    return sig.r.slice(2) + sig.s.slice(2) + sig.v.toString(16).padStart(2, '0')
  }).join('')
  await (await safe.execTransaction(to, 0, data, 0, 0, 0, 0, zero, zero, sigs)).wait()
}

export async function deployAndSeed({ provider, keys, demo, log }) {
  const wallets = (k) => new NonceManager(new Wallet(k, provider))
  const fund = async (addr, eth = '100') => provider.send('anvil_setBalance', [addr, hex(parseEther(eth))])
  const deployerW = new Wallet(keys.deployer, provider)
  const deployer = new NonceManager(deployerW)
  await fund(deployerW.address)
  await fund(new Wallet(keys.faucet).address)
  await fund(new Wallet(keys.sponsorBot).address)
  for (const k of keys.lockerBots) await fund(new Wallet(k).address)

  // Safes (canonical Safe v1.5.0 code, throwaway signers; the Locker owner must be a contract).
  const ownerSafe = await deploySafe(provider, deployer, keys.ownerSigners, 1)
  const guardianSafe = await deploySafe(provider, deployer, keys.guardianSigners, 2)
  log(`seed: owner Safe ${ownerSafe.address}, guardian Safe ${guardianSafe.address} (v${ownerSafe.version})`)

  // Gate 1 contracts. Pilot scope: WIF is the only listed token. Unit and cap are provisional demo values.
  const unit = parseUnits(demo.wifUnit, 18)
  const cap = parseUnits(demo.wifCap, 18)
  const L = artifact('RixorLocker')
  const C = artifact('RixorChallenges')
  const locker = await new ContractFactory(L.abi, L.bytecode, deployer).deploy(ADDR.WIF, ownerSafe.address, guardianSafe.address, [ADDR.WIF], [unit], [cap])
  await locker.waitForDeployment()
  const challenges = await new ContractFactory(C.abi, C.bytecode, deployer).deploy(await locker.getAddress(), demo.minHoldSeconds)
  await challenges.waitForDeployment()
  const lockerAddr = await locker.getAddress()
  const challengesAddr = await challenges.getAddress()
  log(`seed: RixorLocker ${lockerAddr}, RixorChallenges ${challengesAddr} (minHold ${demo.minHoldSeconds}s)`)

  // Labelled demo activity so the app is not empty. All of it is fork WIF on the demo chain.
  const faucet = wallets(keys.faucet)
  const wifFrom = (signer) => new Contract(ADDR.WIF, ERC20, signer)
  const sponsor = wallets(keys.sponsorBot)
  const sponsorAddr = new Wallet(keys.sponsorBot).address
  await (await wifFrom(faucet).transfer(sponsorAddr, parseUnits('1000000', 18))).wait()
  await (await wifFrom(faucet).transfer(ownerSafe.address, parseUnits('600000', 18))).wait()
  const bots = keys.lockerBots.map(wallets)
  const botAddrs = keys.lockerBots.map((k) => new Wallet(k).address)
  for (const a of botAddrs) await (await wifFrom(faucet).transfer(a, parseUnits('300000', 18))).wait()

  const now = (await provider.getBlock('latest')).timestamp
  const params = (title, description, joinIn, endIn, minTier, minUnits) => ({
    tokens: [ADDR.WIF], minTier, minUnitsPerEntry: minUnits, joinDeadline: now + joinIn, endTime: now + endIn,
    goalPoints: 0n, maxParticipants: 200, title, description,
  })
  const ch = (signer) => new Contract(challengesAddr, C.abi, signer)
  await (await wifFrom(sponsor).approve(challengesAddr, parseUnits('250000', 18))).wait()
  await (await ch(sponsor).createChallenge(params(
    'Hold the line (demo seed)',
    'Demo challenge created by the fork backend with fork WIF. Keep your WIF position open until the end to share the pool.',
    2 * DAY, 5 * DAY, 0, 1,
  ), parseUnits('250000', 18))).wait()
  // Season challenge created and funded by the owner Safe through a 2-of-3 Safe transaction.
  const seasonPool = parseUnits('500000', 18)
  const relayer = deployer
  await safeExec(provider, relayer, ownerSafe.address, keys.ownerSigners, ADDR.WIF, new Interface(ERC20).encodeFunctionData('approve', [challengesAddr, seasonPool]))
  await safeExec(provider, relayer, ownerSafe.address, keys.ownerSigners, challengesAddr, new Interface(C.abi).encodeFunctionData('createSeason', [
    params('Season preview (demo seed)', 'Demo Season challenge funded by the demo owner Safe with fork WIF. Committed or Diamond positions only. Not an approved Season budget.', 2 * DAY, 7 * DAY, 1, 2),
    seasonPool,
  ]))

  // Three demo lockers (labelled "demo bot" in the app) lock and join.
  const lockerC = (signer) => new Contract(lockerAddr, L.abi, signer)
  const plan = [
    { amount: '75000', tier: 2, days: 90, season: true },
    { amount: '30000', tier: 1, days: 30, season: true },
    { amount: '15000', tier: 0, days: 0, season: false },
  ]
  for (let i = 0; i < bots.length; i++) {
    const p = plan[i]
    const amt = parseUnits(p.amount, 18)
    await (await wifFrom(bots[i]).approve(lockerAddr, amt)).wait()
    const tx = await lockerC(bots[i]).lock(ADDR.WIF, amt, p.tier, p.days)
    const rc = await tx.wait()
    const ev = rc.logs.map((l) => { try { return new Interface(L.abi).parseLog(l) } catch { return null } }).find((e) => e?.name === 'Locked')
    const positionId = ev.args.positionId ?? ev.args[1]
    await (await ch(bots[i]).join(1, positionId, '0x0000000000000000000000000000000000000000')).wait()
    if (p.season) await (await ch(bots[i]).join(2, positionId, '0x0000000000000000000000000000000000000000')).wait()
  }
  log('seed: demo challenges #1 (community) and #2 (Season) created; 3 demo bots locked and joined')

  return {
    contracts: { locker: lockerAddr, challenges: challengesAddr, wif: ADDR.WIF, ownerSafe: ownerSafe.address, guardianSafe: guardianSafe.address },
    safes: { owner: ownerSafe, guardian: guardianSafe },
    demoAccounts: {
      faucet: new Wallet(keys.faucet).address,
      sponsorBot: sponsorAddr,
      lockerBots: botAddrs,
    },
    seeds: [1, 2],
    params: { unit: unit.toString(), cap: cap.toString(), minHoldSeconds: demo.minHoldSeconds },
  }
}
